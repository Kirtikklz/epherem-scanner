export const RULE_REGISTRY_BY_ID: ReadonlyMap<string, RuleMetadata> = new Map(
  RULE_REGISTRY.map((meta) => [meta.ruleId, meta]),
);

export function ruleMetadata(ruleId: string): RuleMetadata | undefined {
  return RULE_REGISTRY_BY_ID.get(ruleId);
}

export function validateRegistryAgainstCatalog(): string[] {
  const problems: string[] = [];
  const catalogIds = new Set(Object.keys(RULE_CATALOG));
  const registryIds = new Set<string>();
  for (const meta of RULE_REGISTRY) {
    if (registryIds.has(meta.ruleId)) problems.push(`duplicate registry entry: ${meta.ruleId}`);
    registryIds.add(meta.ruleId);
    if (!catalogIds.has(meta.ruleId)) problems.push(`registry rule missing from catalog: ${meta.ruleId}`);
    const catalogEntry = RULE_CATALOG[meta.ruleId];
    if (catalogEntry !== undefined && catalogEntry.error !== meta.error) {
      problems.push(`label drift for ${meta.ruleId}: catalog="${catalogEntry.error}" registry="${meta.error}"`);
    }
    if (meta.error.trim() === '') problems.push(`empty error label: ${meta.ruleId}`);
    if (meta.title.trim() === '') problems.push(`empty title: ${meta.ruleId}`);
    if (meta.remediation.trim() === '') problems.push(`empty remediation: ${meta.ruleId}`);
    if (meta.languages.length === 0) problems.push(`no languages: ${meta.ruleId}`);
  }
  for (const id of catalogIds) {
    if (!registryIds.has(id)) problems.push(`catalog rule missing from registry: ${id}`);
  }
  return problems;
}
